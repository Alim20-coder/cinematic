function initWorksLightbox() {
  const box = document.getElementById('lightbox');
  if (!box) return;
  const img = document.getElementById('lightboxImg');
  const cap = document.getElementById('lightboxCap');
  const count = document.getElementById('lightboxCount');
  const prevBtn = document.getElementById('lightboxPrev');
  const nextBtn = document.getElementById('lightboxNext');
  const closeBtn = document.getElementById('lightboxClose');
  let items = [];
  let index = 0;
  let lastFocus = null;

  function captionFor(fig) {
    const group = fig.closest('.work-project');
    const title = group && group.querySelector('.work-title');
    if (title) return title.textContent.trim();
    const active = document.querySelector('.works-filter-btn.is-active');
    return active ? active.textContent.trim() : '';
  }

  function show(i) {
    index = (i + items.length) % items.length;
    const fig = items[index];
    const text = captionFor(fig);
    img.classList.remove('is-swap');
    void img.offsetWidth;
    img.classList.add('is-swap');
    img.src = fig.querySelector('img').src;
    img.alt = text;
    cap.textContent = text;
    count.textContent = `${index + 1} / ${items.length}`;
    const single = items.length < 2;
    prevBtn.hidden = single;
    nextBtn.hidden = single;
  }

  function open(fig) {
    const panel = fig.closest('.works-panel');
    items = Array.from((panel || document).querySelectorAll('.work-photo'));
    lastFocus = fig;
    box.classList.add('is-open');
    document.body.style.overflow = 'hidden';
    show(items.indexOf(fig));
    closeBtn.focus();
  }

  function close() {
    box.classList.remove('is-open');
    document.body.style.overflow = '';
    img.removeAttribute('src');
    if (lastFocus) lastFocus.focus();
  }

  document.addEventListener('click', (e) => {
    const fig = e.target.closest('.work-photo');
    if (fig && fig.closest('.works-panel')) open(fig);
  });
  document.addEventListener('keydown', (e) => {
    if (box.classList.contains('is-open')) {
      if (e.key === 'Escape') close();
      else if (e.key === 'ArrowLeft') show(index - 1);
      else if (e.key === 'ArrowRight') show(index + 1);
    } else if ((e.key === 'Enter' || e.key === ' ') && e.target.classList && e.target.classList.contains('work-photo')) {
      e.preventDefault();
      open(e.target);
    }
  });
  box.addEventListener('click', (e) => {
    if (e.target === box || e.target.classList.contains('lightbox-stage')) close();
  });
  closeBtn.addEventListener('click', close);
  prevBtn.addEventListener('click', () => show(index - 1));
  nextBtn.addEventListener('click', () => show(index + 1));

  let startX = null;
  box.addEventListener('touchstart', (e) => { startX = e.touches[0].clientX; }, { passive: true });
  box.addEventListener('touchend', (e) => {
    if (startX === null) return;
    const dx = e.changedTouches[0].clientX - startX;
    startX = null;
    if (Math.abs(dx) > 50 && items.length > 1) show(dx < 0 ? index + 1 : index - 1);
  });
}

function initAmbientSmoke() {
  const canvas = document.getElementById('ambientSmokeCanvas');
  if (!canvas) return;
  const ctx = canvas.getContext('2d');
  let width, height;
  let particles = [];
  const particleCount = 65;

  function resize() {
    const parent = canvas.parentElement;
    width = canvas.width = parent.offsetWidth;
    height = canvas.height = parent.offsetHeight;
  }

  class Particle {
    constructor() {
      this.reset(true);
    }

    reset(initial = false) {
      this.x = Math.random() * width;
      this.y = initial ? Math.random() * height : height + Math.random() * 80;
      const type = Math.random();
      if (type < 0.35) {
        this.radius = 45 + Math.random() * 60;
        this.baseAlpha = 0.035 + Math.random() * 0.05;
        this.vy = -(0.12 + Math.random() * 0.18);
        this.vx = (Math.random() - 0.5) * 0.15;
      } else if (type < 0.75) {
        this.radius = 16 + Math.random() * 28;
        this.baseAlpha = 0.08 + Math.random() * 0.14;
        this.vy = -(0.2 + Math.random() * 0.3);
        this.vx = (Math.random() - 0.5) * 0.25;
      } else {
        this.radius = 3 + Math.random() * 7;
        this.baseAlpha = 0.18 + Math.random() * 0.28;
        this.vy = -(0.3 + Math.random() * 0.45);
        this.vx = (Math.random() - 0.5) * 0.35;
      }
      this.pulse = Math.random() * Math.PI * 2;
      this.pulseSpeed = 0.008 + Math.random() * 0.015;
    }

    update() {
      this.x += this.vx;
      this.y += this.vy;
      this.pulse += this.pulseSpeed;

      if (this.y < -this.radius * 2) {
        this.reset(false);
      }
      if (this.x < -this.radius * 2) this.x = width + this.radius;
      if (this.x > width + this.radius * 2) this.x = -this.radius;
    }

    draw() {
      const currentAlpha = this.baseAlpha * (0.7 + 0.3 * Math.sin(this.pulse));
      const grad = ctx.createRadialGradient(this.x, this.y, 0, this.x, this.y, this.radius);
      grad.addColorStop(0, `rgba(240, 245, 255, ${currentAlpha})`);
      grad.addColorStop(0.45, `rgba(180, 205, 235, ${currentAlpha * 0.45})`);
      grad.addColorStop(1, 'rgba(0, 0, 0, 0)');

      ctx.fillStyle = grad;
      ctx.beginPath();
      ctx.arc(this.x, this.y, this.radius, 0, Math.PI * 2);
      ctx.fill();
    }
  }

  resize();
  window.addEventListener('resize', resize);

  for (let i = 0; i < particleCount; i++) {
    particles.push(new Particle());
  }

  function loop() {
    ctx.clearRect(0, 0, width, height);
    for (let i = 0; i < particles.length; i++) {
      particles[i].update();
      particles[i].draw();
    }
    requestAnimationFrame(loop);
  }

  requestAnimationFrame(loop);
}

